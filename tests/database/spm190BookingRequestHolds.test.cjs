// SPM-190 (developer decision of 1 November 2026): a booking request is the
// venue hold. Its expiry is set when it is sent, cleared on approval; overdue
// requests become EXPIRED and free the venue; the coordinator and Venue Staff
// are reminded 24 hours before. Real migration functions in a reduced,
// isolated PostgreSQL fixture; the notification helpers are stand-ins that
// record what was sent. No hosted writes.
const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { PGlite } = require("@electric-sql/pglite");
const root = path.resolve(__dirname, "../..");
const read = (name) => fs.readFileSync(path.join(root, "supabase/migrations", name), "utf8");
const one = async (db, sql, args = []) => (await db.query(sql, args)).rows[0];

const COORDINATOR = 2;
const EVENT = 10;
const HOUR = 60 * 60 * 1000;
const iso = (ms) => new Date(ms).toISOString();

async function setup() {
  const db = new PGlite();
  await db.exec(fs.readFileSync(path.join(root, "tests/fixtures/spm177DatabaseSchema.sql"), "utf8"));
  // The live booking columns these functions read; the reduced fixture has no bookings.
  await db.exec(`
    CREATE TYPE public.booking_status AS ENUM ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED');
    CREATE TABLE public.venue_booking (
      booking_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      event_id integer NOT NULL,
      venue_id integer NOT NULL,
      start_datetime timestamptz NOT NULL,
      end_datetime timestamptz NOT NULL,
      occupied_range tstzrange,
      status public.booking_status NOT NULL DEFAULT 'PENDING',
      updated_at timestamptz NOT NULL DEFAULT now()
    );
    CREATE TABLE public.sent_notice (event_id integer, title text, message text, recipients integer[], action_key text);
    CREATE FUNCTION public._notify_event_users(p_event_id integer, p_title text, p_message text, p_recipients integer[],
      p_type public.notification_type, p_action_key text, p_action_expires_at timestamptz) RETURNS integer LANGUAGE sql AS $$
      INSERT INTO public.sent_notice VALUES (p_event_id, p_title, p_message, p_recipients, p_action_key) RETURNING 1 $$;
    CREATE FUNCTION public._event_coordinator_recipients(p_event public.event) RETURNS integer[] LANGUAGE sql AS $$
      SELECT ARRAY[p_event.coordinator_id] $$;
    CREATE FUNCTION public._venue_staff_recipients(p_except integer) RETURNS integer[] LANGUAGE sql AS $$ SELECT ARRAY[30] $$;
    CREATE FUNCTION public._venue_local_time(p_at timestamptz) RETURNS text LANGUAGE sql AS $$ SELECT p_at::text $$;
  `);
  await db.exec(read("20261101140000_spm190_booking_request_hold_columns.sql"));
  await db.exec(read("20261101140100_spm190_booking_request_holds.sql"));
  await db.exec(read("20261101140200_spm190_approval_expiry_guard.sql"));
  await db.exec(`INSERT INTO public.venue (venue_id,name,address,max_capacity,is_active) VALUES
    (1,'SPM-190 Hall','1 Synthetic Road',300,true),(2,'SPM-190 Annex','1 Synthetic Road',80,true)`);
  await db.exec(`INSERT INTO public."user" (user_id,email,name,role,is_active) VALUES
    (1,'spm190-owner@example.test','Owner','ORGANISER',true),
    (${COORDINATOR},'spm190-coordinator@example.test','Coordinator','COORDINATOR',true)`);
  await db.exec(`INSERT INTO public.event (event_id,organiser_id,coordinator_id,title,purpose,description,start_datetime,end_datetime,expected_attendance,preferred_layout_type,status)
    VALUES (${EVENT},1,${COORDINATOR},'SPM-190 synthetic event','Forum','Synthetic event','2035-01-01T01:00:00Z','2035-01-01T10:00:00Z',150,'NO_PREFERENCE','PLANNING')`);
  return db;
}

// A pending request whose occupied range starts `startsIn` from now.
const request = async (db, startsIn, { venue = 1, holdExpiresAt } = {}) => {
  const start = Date.now() + startsIn;
  const row = await one(db,
    `INSERT INTO public.venue_booking (event_id, venue_id, start_datetime, end_datetime, occupied_range${holdExpiresAt ? ", hold_expires_at" : ""})
     VALUES ($1, $2, $3, $4, tstzrange($3::timestamptz, $4::timestamptz, '[)')${holdExpiresAt ? ", $5" : ""})
     RETURNING booking_id, status::text AS status, hold_expires_at`,
    [EVENT, venue, iso(start), iso(start + 2 * HOUR), ...(holdExpiresAt ? [holdExpiresAt] : [])]);
  return { ...row, start };
};
const booking = (db, id) => one(db, "SELECT status::text AS status, hold_expires_at, hold_reminded_at FROM public.venue_booking WHERE booking_id = $1", [id]);
const notices = async (db) => (await db.query("SELECT title, recipients, action_key FROM public.sent_notice ORDER BY action_key")).rows;

test("[SPM-190] a request sent well ahead holds the venue for 7 days", async () => {
  const db = await setup();
  try {
    const before = Date.now();
    const sent = await request(db, 30 * 24 * HOUR);
    const holds = new Date(sent.hold_expires_at).getTime() - before;
    assert.ok(Math.abs(holds - 7 * 24 * HOUR) < 60 * 1000, `held for ${holds} ms`);
  } finally { await db.close(); }
});

test("[SPM-190] a request close to the event holds until 24 hours before setup, or until setup inside 24 hours", async () => {
  const db = await setup();
  try {
    const soon = await request(db, 3 * 24 * HOUR);
    assert.equal(new Date(soon.hold_expires_at).getTime(), new Date(soon.start - 24 * HOUR).getTime());
    const late = await request(db, 5 * HOUR, { venue: 2 });
    assert.equal(new Date(late.hold_expires_at).getTime(), new Date(late.start).getTime());
  } finally { await db.close(); }
});

test("[SPM-190] approval clears the expiry; rejection keeps it for the record", async () => {
  const db = await setup();
  try {
    const approved = await request(db, 30 * 24 * HOUR);
    const rejected = await request(db, 30 * 24 * HOUR, { venue: 2 });
    await db.query("UPDATE public.venue_booking SET status = 'APPROVED' WHERE booking_id = $1", [approved.booking_id]);
    await db.query("UPDATE public.venue_booking SET status = 'REJECTED' WHERE booking_id = $1", [rejected.booking_id]);
    assert.equal((await booking(db, approved.booking_id)).hold_expires_at, null);
    assert.notEqual((await booking(db, rejected.booking_id)).hold_expires_at, null);
  } finally { await db.close(); }
});

test("[SPM-190][Week 7 change 4] an overdue request expires, frees the venue and tells the coordinator once", async () => {
  const db = await setup();
  try {
    const overdue = await request(db, 30 * 24 * HOUR, { holdExpiresAt: iso(Date.now() - 60 * 1000) });
    const current = await request(db, 30 * 24 * HOUR, { venue: 2 });

    assert.equal((await one(db, "SELECT public.expire_overdue_venue_bookings(NULL, 100) AS n")).n, 1);
    assert.equal((await booking(db, overdue.booking_id)).status, "EXPIRED");
    assert.equal((await booking(db, current.booking_id)).status, "PENDING");
    assert.deepEqual(await notices(db), [{ title: "Venue request expired", recipients: [COORDINATOR], action_key: `BOOKING_HOLD_EXPIRED:${overdue.booking_id}` }]);
    const log = await one(db, "SELECT action, audience FROM public.activity_log WHERE entity_id = $1", [EVENT]);
    assert.deepEqual(log, { action: "VENUE_BOOKING_EXPIRED", audience: "STAFF_ONLY" });

    // A second run finds nothing to do.
    assert.equal((await one(db, "SELECT public.expire_overdue_venue_bookings(NULL, 100) AS n")).n, 0);
    assert.equal((await notices(db)).length, 1);
  } finally { await db.close(); }
});

test("[SPM-190] the booking request path expires only the venues it locked", async () => {
  const db = await setup();
  try {
    const hall = await request(db, 30 * 24 * HOUR, { holdExpiresAt: iso(Date.now() - 60 * 1000) });
    const annex = await request(db, 30 * 24 * HOUR, { venue: 2, holdExpiresAt: iso(Date.now() - 60 * 1000) });

    assert.equal((await one(db, "SELECT public.expire_overdue_venue_bookings(ARRAY[1], 500) AS n")).n, 1);
    assert.equal((await booking(db, hall.booking_id)).status, "EXPIRED");
    assert.equal((await booking(db, annex.booking_id)).status, "PENDING");
  } finally { await db.close(); }
});

test("[SPM-190][Week 7 change 4] the coordinator and Venue Staff are reminded once, 24 hours before expiry", async () => {
  const db = await setup();
  try {
    const due = await request(db, 30 * 24 * HOUR, { holdExpiresAt: iso(Date.now() + 5 * HOUR) });
    await request(db, 30 * 24 * HOUR, { venue: 2, holdExpiresAt: iso(Date.now() + 48 * HOUR) });

    assert.equal((await one(db, "SELECT public.remind_expiring_venue_bookings(100) AS n")).n, 1);
    assert.notEqual((await booking(db, due.booking_id)).hold_reminded_at, null);
    assert.deepEqual(await notices(db), [
      { title: "Venue request awaiting decision", recipients: [COORDINATOR], action_key: `BOOKING_HOLD_EXPIRING:${due.booking_id}` },
      { title: "Venue request needs a decision", recipients: [30], action_key: `BOOKING_HOLD_EXPIRING:${due.booking_id}:VENUE_STAFF` },
    ]);
    assert.equal((await one(db, "SELECT public.remind_expiring_venue_bookings(100) AS n")).n, 0);
  } finally { await db.close(); }
});

test("[SPM-190] existing pending requests get an expiry when the migration runs", async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
      CREATE TYPE public.booking_status AS ENUM ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED');
      CREATE TYPE public.notification_type AS ENUM ('BOOKING_UPDATE');
      CREATE TABLE public.event (event_id integer PRIMARY KEY);
      CREATE TABLE public.venue (venue_id integer PRIMARY KEY, name text);
      CREATE TABLE public.venue_booking (booking_id integer PRIMARY KEY, event_id integer, venue_id integer,
        start_datetime timestamptz NOT NULL, end_datetime timestamptz NOT NULL, occupied_range tstzrange,
        status public.booking_status NOT NULL, updated_at timestamptz DEFAULT now());
      INSERT INTO public.venue_booking VALUES
        (1, 1, 1, now() + interval '30 days', now() + interval '30 days 2 hours', NULL, 'PENDING'),
        (2, 1, 1, now() + interval '30 days', now() + interval '30 days 2 hours', NULL, 'APPROVED');
    `);
    await db.exec(read("20261101140000_spm190_booking_request_hold_columns.sql"));
    await db.exec(read("20261101140100_spm190_booking_request_holds.sql"));
    const rows = (await db.query("SELECT booking_id, hold_expires_at IS NOT NULL AS has_expiry FROM public.venue_booking ORDER BY booking_id")).rows;
    assert.deepEqual(rows, [{ booking_id: 1, has_expiry: true }, { booking_id: 2, has_expiry: false }]);
  } finally { await db.close(); }
});

test("[SPM-190] approval asks the database whether a request's hold has passed", async () => {
  const db = await setup();
  try {
    const overdue = await request(db, 30 * 24 * HOUR, { holdExpiresAt: iso(Date.now() - 60 * 1000) });
    const current = await request(db, 30 * 24 * HOUR, { venue: 2 });
    const expired = async (id) => (await one(db, "SELECT public.venue_booking_hold_expired($1) AS expired", [id])).expired;
    assert.equal(await expired(overdue.booking_id), true);
    assert.equal(await expired(current.booking_id), false);
    assert.equal(await expired(999999), false);
  } finally { await db.close(); }
});

