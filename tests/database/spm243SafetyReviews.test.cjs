test("[SPM-247 AC4] one officer claims an open round; a second claim and other roles are refused", async () => {
  const { event, round } = await reviewEvent();
  const claimed = await claim(round.review_id);
  assert.equal(claimed.claimed_by, OFFICER);
  assert.ok(claimed.claimed_at);
  await refused(claim(round.review_id, OTHER_OFFICER), "ROUND_NOT_CLAIMABLE");
  await refused(claim(round.review_id, COORDINATOR), "FORBIDDEN");
  await refused(claim(999999), "REVIEW_NOT_FOUND");
  assert.deepEqual(await history(event.event_id), [
    { action: "SAFETY_REVIEW_CLAIMED", audience: "STAFF_ONLY", details: "Safety review round 1 claimed." },
  ]);
});

test("[SPM-247 AC5][TC-07][TC-08] the claimant hands back an undecided round; progress is cleared", async () => {
  const { event, round } = await reviewEvent({ claimedBy: OFFICER });
  await saveProgress(round.review_id, { checklist: { layout: { result: "SATISFACTORY", comment: "" } }, internalNotes: "Draft notes" });
  await refused(handBack(round.review_id, OTHER_OFFICER), "NOT_CLAIMANT");
  await refused(handBack(round.review_id, OFFICER, "x".repeat(501)), "INVALID_SAFETY_REVIEW");

  const returned = await handBack(round.review_id, OFFICER, "Out sick tomorrow");
  assert.equal(returned.claimed_by, null);
  assert.equal(returned.checklist, null);
  assert.equal(returned.internal_notes, null);
  assert.equal(returned.status, "OPEN");
  const entries = await history(event.event_id);
  assert.deepEqual(entries.at(-1), {
    action: "SAFETY_REVIEW_HANDED_BACK",
    audience: "STAFF_ONLY",
    details: "Safety review round 1 handed back to the queue. Note: Out sick tomorrow",
  });
  // TC-07: SO1 can no longer save progress; SO2 can claim it.
  await refused(saveProgress(round.review_id, { internalNotes: "Late" }), "NOT_CLAIMANT");
  assert.equal((await claim(round.review_id, OTHER_OFFICER)).claimed_by, OTHER_OFFICER);

  // TC-08: a decided round cannot be handed back.
  const decided = await reviewEvent({ claimedBy: OFFICER });
  await decide(decided.round.review_id, { outcome: "APPROVED", checklist: checklist() });
  await refused(handBack(decided.round.review_id), "ROUND_NOT_OPEN");
});

test("[SPM-247 AC7][TC-11] progress is partial, keeps unsent fields and rejects bad shapes", async () => {
  const { round } = await reviewEvent({ claimedBy: OFFICER });
  await saveProgress(round.review_id, { checklist: { layout: { result: "NOT_SATISFACTORY" } }, organiserComment: "Please widen the aisles." });
  const kept = await saveProgress(round.review_id, { internalNotes: "Check fire plan" });
  assert.deepEqual(kept.checklist, { layout: { result: "NOT_SATISFACTORY" } });
  assert.equal(kept.organiser_comment, "Please widen the aisles.");
  assert.equal(kept.internal_notes, "Check fire plan");

  await refused(saveProgress(round.review_id, { status: "APPROVED" }), "INVALID_SAFETY_REVIEW");
  await refused(saveProgress(round.review_id, { checklist: { layout: { result: "MAYBE" } } }), "INVALID_SAFETY_REVIEW");
  await refused(saveProgress(round.review_id, { checklist: { parking: { result: "SATISFACTORY" } } }), "INVALID_SAFETY_REVIEW");
  await refused(saveProgress(round.review_id, { requestedChanges: ["", "ok"] }), "INVALID_SAFETY_REVIEW");
  const cleared = await saveProgress(round.review_id, { checklist: null });
  assert.equal(cleared.checklist, null);
});

test("[SPM-249 AC8][TC-12][TC-13] approval keeps SAFETY_REVIEW, needs no NOT_SATISFACTORY and notifies coordinator and staff", async () => {
  const { event, round } = await reviewEvent({ claimedBy: OFFICER });
  await refused(
    decide(round.review_id, { outcome: "APPROVED", checklist: checklist({ layout: { result: "NOT_SATISFACTORY", comment: "Blocked exit" } }) }),
    "SAFETY_FACTOR_NOT_SATISFACTORY"
  );
  assert.equal((await roundRow(round.review_id)).status, "OPEN");

  const result = await decide(round.review_id, {
    outcome: "APPROVED",
    checklist: checklist({ accessibility: { result: "NOT_APPLICABLE", comment: "No access needs listed" } }),
    organiserComment: "All clear.",
    internalNotes: "Checked with venue.",
  });
  assert.equal(result.superseded, false);
  assert.equal(result.review.status, "APPROVED");
  assert.equal(result.review.decided_by, OFFICER);
  assert.equal((await eventRow(event.event_id)).status, "SAFETY_REVIEW");
  assert.deepEqual((await history(event.event_id)).at(-1), {
    action: "SAFETY_REVIEW_APPROVED", audience: "ORGANISER_SAFE", details: "Safety review round 1 approved.",
  });
  assert.deepEqual(await recipients(event.event_id), [
    { title: "Safety review approved", recipient_id: COORDINATOR },
    { title: "Safety review approved", recipient_id: VENUE_STAFF },
    { title: "Safety review approved", recipient_id: TECH },
  ]);
});

test("[SPM-249 AC7][TC-10] a decision needs every factor, and a comment unless SATISFACTORY", async () => {
  const { round } = await reviewEvent({ claimedBy: OFFICER });
  const missing = checklist();
  delete missing.emergencyAccess;
  await refused(decide(round.review_id, { outcome: "APPROVED", checklist: missing }), "INVALID_SAFETY_REVIEW");
  await assert.rejects(
    decide(round.review_id, { outcome: "CHANGES_REQUESTED", checklist: checklist({ layout: { result: "NOT_SATISFACTORY", comment: " " } }), requestedChanges: ["Wider aisles"] }),
    (error) => /layout:COMMENT_REQUIRED/.test(error.detail || "")
  );
  await assert.rejects(
    decide(round.review_id, { outcome: "APPROVED", checklist: missing }),
    (error) => /emergencyAccess:REQUIRED/.test(error.detail || "")
  );
  await refused(decide(round.review_id, { outcome: "PASSED", checklist: checklist() }), "INVALID_SAFETY_REVIEW");
});

test("[SPM-249 AC9][TC-14] changes requested returns the event to PLANNING and resets nothing", async () => {
  const { event, round, bookingId } = await reviewEvent({ claimedBy: OFFICER });
  await refused(decide(round.review_id, { outcome: "CHANGES_REQUESTED", checklist: checklist() }), "INVALID_SAFETY_REVIEW");
  const result = await decide(round.review_id, {
    outcome: "CHANGES_REQUESTED",
    checklist: checklist({ layout: { result: "NOT_SATISFACTORY", comment: "Aisles too narrow" } }),
    requestedChanges: ["Widen the aisles to 1.5 m", "Add a second exit sign"],
  });
  assert.equal(result.review.status, "CHANGES_REQUESTED");
  assert.deepEqual(result.review.requested_changes, ["Widen the aisles to 1.5 m", "Add a second exit sign"]);
  assert.equal((await eventRow(event.event_id)).status, "PLANNING");
  assert.equal((await one("SELECT status FROM public.venue_booking WHERE booking_id = $1", [bookingId])).status, "APPROVED");
  assert.equal((await history(event.event_id)).at(-1).action, "SAFETY_CHANGES_REQUESTED");
});

test("[SPM-249 AC10][TC-15][TC-16] rejection names active bookings of this event and never rejects the event", async () => {
  const { event, round, bookingId } = await reviewEvent({ claimedBy: OFFICER });
  const other = await reviewEvent();
  const base = { outcome: "REJECTED", checklist: checklist({ venueRestrictions: { result: "NOT_SATISFACTORY", comment: "No fire exit" } }) };
  await refused(decide(round.review_id, { ...base, rejectedBookings: [] }), "INVALID_SAFETY_REVIEW");
  await assert.rejects(
    decide(round.review_id, { ...base, rejectedBookings: [{ bookingId: other.bookingId, reason: "Unsafe" }] }),
    (error) => /rejectedBookings:NOT_ACTIVE_ON_EVENT/.test(error.detail || "")
  );

  const result = await decide(round.review_id, { ...base, rejectedBookings: [{ bookingId, reason: "No second fire exit" }] });
  assert.equal(result.review.status, "REJECTED");
  assert.equal((await eventRow(event.event_id)).status, "PLANNING");
  assert.equal((await one("SELECT status FROM public.venue_booking WHERE booking_id = $1", [bookingId])).status, "APPROVED");
  assert.deepEqual(
    (await db.query("SELECT booking_id, reason FROM public.safety_review_rejected_bookings WHERE review_id = $1", [round.review_id])).rows,
    [{ booking_id: bookingId, reason: "No second fire exit" }]
  );
  assert.equal((await history(event.event_id)).at(-1).action, "SAFETY_VENUES_REJECTED");
});

