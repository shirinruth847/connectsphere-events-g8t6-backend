// SPM-243 safety review functions (SPM-247, SPM-249, SPM-250) on in-memory
// PostgreSQL. These tests never connect to hosted Supabase and cannot test
// separate-connection races; the integration suites cover those.
const { test, beforeEach } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { PGlite } = require(process.env.PGLITE_MODULE || "@electric-sql/pglite");

const root = path.resolve(__dirname, "../..");
const read = (name) => fs.readFileSync(path.join(root, "supabase/migrations", name), "utf8");
const functionSql = (sql, name) => {
  const match = sql.match(new RegExp(`CREATE (?:OR REPLACE )?FUNCTION public\\.${name}\\([\\s\\S]*?\\n\\$\\$;`));
  assert.ok(match, `Function ${name} must exist in its source migration`);
  return match[0];
};

const FACTORS = ["attendanceCapacity", "layout", "emergencyAccess", "accessibility", "equipmentPlacement", "venueRestrictions"];
const checklist = (overrides = {}) =>
  Object.fromEntries(FACTORS.map((factor) => [factor, { result: "SATISFACTORY", comment: "" }]).concat(Object.entries(overrides)));

// Users: 1 owner, 2 coordinator, 3 and 4 Safety Officers, 5 Venue Staff, 6 Technical Support.
const OWNER = 1;
const COORDINATOR = 2;
const OFFICER = 3;
const OTHER_OFFICER = 4;
const VENUE_STAFF = 5;
const TECH = 6;

let db;
const one = async (sql, values = []) => (await db.query(sql, values)).rows[0];
const call = async (sql, values = []) => (await one(`SELECT ${sql} AS result`, values)).result;
const refused = (promise, message) => assert.rejects(promise, (error) => {
  assert.match(error.message, new RegExp(message));
  return true;
});

const claim = (reviewId, actor = OFFICER) => call("public.claim_safety_review($1, $2)", [reviewId, actor]);
const handBack = (reviewId, actor = OFFICER, note = null) => call("public.hand_back_safety_review($1, $2, $3)", [reviewId, actor, note]);
const saveProgress = (reviewId, progress, actor = OFFICER) => call("public.save_safety_review_progress($1, $2, $3::jsonb)", [reviewId, actor, JSON.stringify(progress)]);
const decide = (reviewId, decision, { actor = OFFICER, version = 1, key = null } = {}) =>
  call("public.decide_safety_review($1, $2, $3::jsonb, $4, $5, $6)", [reviewId, actor, JSON.stringify(decision), version, key, key ? "a".repeat(64) : null]);

let nextDay = 0;
// An event in SAFETY_REVIEW with an approved venue booking, approved equipment
// and an open round for arrangement version 1.
const reviewEvent = async ({ claimedBy = null } = {}) => {
  nextDay += 1;
  const start = new Date(Date.UTC(2030, 5, nextDay, 9)).toISOString();
  const end = new Date(Date.UTC(2030, 5, nextDay, 11)).toISOString();
  const event = await one(
    `INSERT INTO public.event (organiser_id, coordinator_id, title, status, start_datetime, end_datetime, expected_attendance)
     VALUES ($1, $2, $3, 'SAFETY_REVIEW', $4, $5, 50) RETURNING *`,
    [OWNER, COORDINATOR, `spm243 event ${nextDay}`, start, end]
  );
  const booking = await one(
    "INSERT INTO public.venue_booking (room_id, event_id, start_datetime, end_datetime, status, reviewed_by) VALUES (1, $1, $2, $3, 'APPROVED', $4) RETURNING booking_id",
    [event.event_id, start, end, VENUE_STAFF]
  );
  await db.query("INSERT INTO public.equipment_request (equipment_id, event_id, status, reviewed_by) VALUES (1, $1, 'APPROVED', $2)", [event.event_id, TECH]);
  const round = await one(
    `INSERT INTO public.safety_reviews (event_id, round_number, arrangement_version, submitted_by, claimed_by, claimed_at)
     VALUES ($1, 1, 1, $2, $3, CASE WHEN $3::integer IS NULL THEN NULL ELSE now() END) RETURNING *`,
    [event.event_id, COORDINATOR, claimedBy]
  );
  return { event, round, bookingId: booking.booking_id };
};

const eventRow = (eventId) => one("SELECT * FROM public.event WHERE event_id = $1", [eventId]);
const roundRow = (reviewId) => one("SELECT * FROM public.safety_reviews WHERE review_id = $1", [reviewId]);
const history = async (eventId) => (await db.query("SELECT action, audience, details FROM public.activity_log WHERE entity_id = $1 ORDER BY log_id", [eventId])).rows;
const recipients = async (eventId) => (await db.query(
  "SELECT n.title, r.recipient_id FROM public.notification n JOIN public.notification_recipient r USING (notification_id) WHERE n.event_id = $1 ORDER BY n.notification_id, r.recipient_id",
  [eventId]
)).rows;

