test("[SPM-249 AC11][TC-18] a decision after the arrangements changed supersedes the round instead", async () => {
  const { event, round } = await reviewEvent({ claimedBy: OFFICER });
  // A change that raised the version without superseding the review itself.
  await db.query("UPDATE public.event SET arrangement_version = 2 WHERE event_id = $1", [event.event_id]);
  const result = await decide(round.review_id, { outcome: "APPROVED", checklist: checklist() }, { version: 1 });
  assert.equal(result.superseded, true);
  assert.equal(result.review.status, "SUPERSEDED");
  assert.equal((await eventRow(event.event_id)).status, "PLANNING");
  assert.deepEqual((await recipients(event.event_id)).map((row) => row.recipient_id), [COORDINATOR, OFFICER]);

  // A stale page whose round is still current is refused without a change.
  const current = await reviewEvent({ claimedBy: OFFICER });
  await refused(decide(current.round.review_id, { outcome: "APPROVED", checklist: checklist() }, { version: 7 }), "ARRANGEMENTS_CHANGED");
  assert.equal((await roundRow(current.round.review_id)).status, "OPEN");
});

test("[SPM-250 AC12][TC-18][TC-19] superseding closes an open round, voids an approval and leaves other states alone", async () => {
  const open = await reviewEvent({ claimedBy: OFFICER });
  const closed = await call("public._supersede_safety_review($1, NULL, $2)", [open.event.event_id, "Venue blocked."]);
  assert.equal(closed.supersededReviewId, open.round.review_id);
  assert.equal(closed.statusChanged, true);
  assert.equal((await roundRow(open.round.review_id)).status, "SUPERSEDED");
  const after = await eventRow(open.event.event_id);
  assert.deepEqual({ status: after.status, arrangement_version: after.arrangement_version }, { status: "PLANNING", arrangement_version: 2 });
  assert.equal((await history(open.event.event_id)).at(-1).action, "SAFETY_REVIEW_SUPERSEDED");
  // The decision from the open page is now refused.
  await refused(decide(open.round.review_id, { outcome: "APPROVED", checklist: checklist() }, { version: 1 }), "ROUND_NOT_OPEN");

  const approved = await reviewEvent({ claimedBy: OFFICER });
  await decide(approved.round.review_id, { outcome: "APPROVED", checklist: checklist() });
  await call("public.record_arrangement_change($1, $2, $3)", [approved.event.event_id, COORDINATOR, "Expected attendance changed."]);
  assert.equal((await roundRow(approved.round.review_id)).status, "APPROVED");
  assert.equal((await eventRow(approved.event.event_id)).status, "PLANNING");
  const message = await one("SELECT message FROM public.notification WHERE event_id = $1 AND title = 'Safety review superseded'", [approved.event.event_id]);
  assert.match(message.message, /safety approval no longer counts/);

  const planning = await reviewEvent();
  await db.query("UPDATE public.safety_reviews SET status = 'SUPERSEDED', superseded_at = now() WHERE event_id = $1", [planning.event.event_id]);
  await db.query("UPDATE public.event SET status = 'PLANNING' WHERE event_id = $1", [planning.event.event_id]);
  const untouched = await call("public._supersede_safety_review($1, NULL, NULL)", [planning.event.event_id]);
  assert.equal(untouched.statusChanged, false);
  assert.equal((await eventRow(planning.event.event_id)).arrangement_version, 2);
  await refused(call("public.record_arrangement_change($1, $2, NULL)", [planning.event.event_id, 999]), "FORBIDDEN");
});

