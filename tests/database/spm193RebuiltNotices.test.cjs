const coordinatorNotice = (eventId) =>
  one(
    `SELECT n.title, n.message FROM public.notification AS n JOIN public.notification_recipient AS r USING (notification_id)
      WHERE n.event_id = $1 AND r.recipient_id = $2`,
    [eventId, COORDINATOR]
  );

let nextDay = 0;
const reviewEvent = async (label = null) => {
  nextDay += 1;
  const start = new Date(Date.UTC(2030, 6, nextDay, 9)).toISOString();
  const end = new Date(Date.UTC(2030, 6, nextDay, 11)).toISOString();
  const event = await one(
    `INSERT INTO public.event (organiser_id, coordinator_id, title, status, start_datetime, end_datetime, expected_attendance)
     VALUES ($1, $2, $3, 'SAFETY_REVIEW', $4, $5, 50) RETURNING *`,
    [OWNER, COORDINATOR, `spm193 event ${nextDay}`, start, end]
  );
  const booking = await one(
    "INSERT INTO public.venue_booking (room_id, event_id, start_datetime, end_datetime, status, reviewed_by, label) VALUES (1, $1, $2, $3, 'APPROVED', $4, $5) RETURNING booking_id",
    [event.event_id, start, end, VENUE_STAFF, label]
  );
  const round = await one(
    `INSERT INTO public.safety_reviews (event_id, round_number, arrangement_version, submitted_by, claimed_by, claimed_at)
     VALUES ($1, 1, 1, $2, $3, now()) RETURNING *`,
    [event.event_id, COORDINATOR, OFFICER]
  );
  return { event, round, bookingId: booking.booking_id };
};

