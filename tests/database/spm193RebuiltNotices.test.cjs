test("[SPM-193-TC-08] approval tells the coordinator to confirm; the event stays in SAFETY_REVIEW (Master 5.2)", async () => {
  const { event, round } = await reviewEvent();
  await decide(round.review_id, { outcome: "APPROVED", checklist: checklist() });
  const notice = await coordinatorNotice(event.event_id);
  assert.equal(notice.title, "Safety review approved");
  assert.match(notice.message, /You can now confirm it\.$/);
  assert.equal((await one("SELECT status::text AS s FROM public.event WHERE event_id = $1", [event.event_id])).s, "SAFETY_REVIEW");
});

test("[SPM-193-TC-09] changes requested name each change and the comment, never the internal notes", async () => {
  const { event, round } = await reviewEvent();
  await decide(round.review_id, {
    outcome: "CHANGES_REQUESTED",
    checklist: checklist({ layout: { result: "NOT_SATISFACTORY", comment: "Aisles too narrow" } }),
    requestedChanges: ["Venue layout: widen the aisles to 1.5 m.", "Add a second exit sign"],
    organiserComment: "Aisles are below the fire code minimum.",
    internalNotes: "Officer to recheck on site.",
  });
  const notice = await coordinatorNotice(event.event_id);
  assert.equal(notice.title, "Safety review changes requested");
  assert.ok(notice.message.endsWith(
    "The event is back in planning. Changes needed: Venue layout: widen the aisles to 1.5 m; Add a second exit sign. Comment: Aisles are below the fire code minimum."
  ));
  assert.ok(!notice.message.includes("recheck on site"));
  assert.equal((await one("SELECT status::text AS s FROM public.event WHERE event_id = $1", [event.event_id])).s, "PLANNING");
});

test("[SPM-193-AC7] a rejection names each rejected booking with its reason", async () => {
  const labelled = await reviewEvent("Main hall");
  await decide(labelled.round.review_id, {
    outcome: "REJECTED",
    checklist: checklist({ venueRestrictions: { result: "NOT_SATISFACTORY", comment: "No fire exit" } }),
    rejectedBookings: [{ bookingId: labelled.bookingId, reason: "No second fire exit." }],
  });
  assert.ok((await coordinatorNotice(labelled.event.event_id)).message.endsWith(
    "rejected 1 venue booking(s). The event is back in planning. Main hall at Synthetic Hall: No second fire exit."
  ));

  const unlabelled = await reviewEvent();
  await decide(unlabelled.round.review_id, {
    outcome: "REJECTED",
    checklist: checklist({ venueRestrictions: { result: "NOT_SATISFACTORY", comment: "No fire exit" } }),
    rejectedBookings: [{ bookingId: unlabelled.bookingId, reason: "Ceiling height too low" }],
  });
  assert.ok((await coordinatorNotice(unlabelled.event.event_id)).message.endsWith("Synthetic Hall: Ceiling height too low."));
});

test("[SPM-193-TC-02] reassignment gives the previous coordinator an ASSIGNMENT_ENDED notice and the new one an assignment", async () => {
  const { event_id: eventId } = await one(
    `INSERT INTO public.event (organiser_id, coordinator_id, title, status, start_datetime, end_datetime, expected_attendance)
     VALUES (1, 2, 'spm193 reassigned', 'PLANNING', '2031-02-01T09:00:00Z', '2031-02-01T11:00:00Z', 50) RETURNING event_id`
  );
  await db.query("INSERT INTO public.event_assignments (event_id, coordinator_id, assigned_by) VALUES ($1, 2, 7)", [eventId]);
  await one("SELECT public.reassign_event_coordinator($1, $2, $3, $4) AS r", [eventId, COORDINATOR_TWO, COORDINATOR, LEAD]);

  assert.deepEqual(await typesOf(eventId), [
    { title: "Event coordinator changed", type: "STATUS_CHANGE", recipients: [OWNER] },
    { title: "Event assignment ended", type: "ASSIGNMENT_ENDED", recipients: [COORDINATOR] },
    { title: "New event coordination assignment", type: "STATUS_CHANGE", recipients: [COORDINATOR_TWO] },
  ]);
  // A retry with the same expected coordinator is refused and adds nothing.
  await assert.rejects(
    one("SELECT public.reassign_event_coordinator($1, $2, $3, $4) AS r", [eventId, COORDINATOR_TWO, COORDINATOR, LEAD]),
    /ASSIGNMENT_CHANGED/
  );
  assert.equal((await typesOf(eventId)).length, 3);
});

test("[SPM-193-AC2] the backfill retypes only 'Event assignment ended' notices sent to former coordinators", async () => {
  assert.deepEqual(await typesOf(legacyEventId), [
    { title: "Event assignment ended", type: "ASSIGNMENT_ENDED", recipients: [COORDINATOR] },
    { title: "Event assignment ended", type: "STATUS_CHANGE", recipients: [OWNER] },
    { title: "Event coordinator changed", type: "STATUS_CHANGE", recipients: [COORDINATOR] },
  ]);
});
