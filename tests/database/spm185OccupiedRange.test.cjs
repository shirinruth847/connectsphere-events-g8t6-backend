// SPM-185 occupied ranges on in-memory PostgreSQL: the SPM-179 venue link
// migration it builds on, then both SPM-185 files, the backfill re-check, the
// exclusion constraint and racing inserts. These tests never connect to hosted
// Supabase. PGlite has one session, so the race test proves that two inserts
// sent together cannot both commit; it does not reproduce two hosted clients
// waiting on each other's uncommitted rows.
const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const pgliteModule = process.env.PGLITE_MODULE || "@electric-sql/pglite";
const { PGlite } = require(pgliteModule);
const { btree_gist } = require(`${pgliteModule}/contrib/btree_gist`);
const root = path.resolve(__dirname, "../..");
const migrationPath = (file) => path.join(root, "supabase/migrations", file);
const read = (file) => fs.readFileSync(migrationPath(file), "utf8");
// SPM-185 builds on the SPM-179 venue link; until that migration reaches this
// branch the suite is skipped rather than run against a schema it never meets.
const VENUE_LINK = "20261028161211_spm179_venue_booking_venue_link.sql";
const skip = fs.existsSync(migrationPath(VENUE_LINK)) ? false : `needs ${VENUE_LINK} (SPM-179)`;
const VENUE_LINK_MIGRATION = skip ? "" : read(VENUE_LINK);
const NO_OVERLAP_MIGRATION = read("20261030120000_spm185_booking_no_overlap.sql");
const BACKFILL_MIGRATION = read("20261030120100_spm185_backfill_occupied_range.sql");
const touchMigration = read("20261021090000_spm181_booking_id_and_updated_at.sql");
const TOUCH_TRIGGER = touchMigration.slice(
  touchMigration.indexOf("CREATE FUNCTION public._touch_venue_booking_updated_at"),
  touchMigration.indexOf("INSERT INTO supabase_migrations")
);
const EDITED_AT = "2026-01-01T00:00:00.000Z";

// Venues use the backfill's IDs: 1 (45/45), 45 (30/45), 48 (0/0) have MongoDB
// minutes; 68 is a fixture venue without them. Rooms 2 and 5 share venue 45.
// Every event spans 2026-2028, so booking windows always lie within one.
async function setup(t, { bookings = [] } = {}) {
  const db = new PGlite({ extensions: { btree_gist } });
  t.after(() => db.close());
  await db.exec(`
    CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
    CREATE SCHEMA extensions;
    CREATE TYPE public.booking_status AS ENUM ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED');
    CREATE TABLE public.venue (
      venue_id integer PRIMARY KEY, name text NOT NULL, address text NOT NULL DEFAULT '1 Test Road',
      max_capacity integer NOT NULL DEFAULT 100
    );
    CREATE TABLE public.room (room_id integer PRIMARY KEY, venue_id integer NOT NULL REFERENCES public.venue (venue_id));
    CREATE TABLE public.event (event_id integer PRIMARY KEY, start_datetime timestamptz, end_datetime timestamptz);
    CREATE TABLE public.venue_booking (
      booking_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      room_id integer NOT NULL REFERENCES public.room (room_id),
      event_id integer NOT NULL REFERENCES public.event (event_id),
      start_datetime timestamptz NOT NULL,
      end_datetime timestamptz NOT NULL,
      status public.booking_status NOT NULL DEFAULT 'PENDING',
      updated_at timestamptz NOT NULL DEFAULT now()
    );
    INSERT INTO public.venue (venue_id, name) VALUES (1, 'Hall'), (45, 'Grand Hall'), (48, 'Conflict Lab'), (68, 'Fixture Hall');
    INSERT INTO public.room VALUES (1, 1), (2, 45), (3, 48), (4, 68), (5, 45);
    INSERT INTO public.event SELECT g, '2026-01-01T00:00:00Z', '2029-01-01T00:00:00Z' FROM generate_series(1, 6000) AS g;
  `);
  await db.exec(TOUCH_TRIGGER);
  for (const [bookingId, roomId, start, end, status = "APPROVED"] of bookings) {
    await db.query(
      `INSERT INTO public.venue_booking (booking_id, room_id, event_id, start_datetime, end_datetime, status, updated_at)
       OVERRIDING SYSTEM VALUE VALUES ($1, $2, $1, $3, $4, $5, $6)`,
      [bookingId, roomId, start, end, status, EDITED_AT]
    );
  }
  await db.exec(VENUE_LINK_MIGRATION);
  return db;
}

const migrate = (db) => db.transaction(async (tx) => {
  await tx.exec(NO_OVERLAP_MIGRATION);
  await tx.exec(BACKFILL_MIGRATION);
});

const sgt = (time, day = "2026-11-04") => `${day}T${time}:00+08:00`;

// Each new booking belongs to its own event: SPM-179 allows one active booking
// per event and venue.
let nextEventId = 5000;
const insertBooking = (db, roomId, start, end, setup, turnaround, status = "PENDING") => db.query(
  `INSERT INTO public.venue_booking (room_id, event_id, start_datetime, end_datetime, status, occupied_range)
   VALUES ($1, $7, $2, $3, $4, public.venue_occupied_range($2, $3, $5, $6))
   RETURNING booking_id, venue_id`,
  [roomId, start, end, status, setup, turnaround, nextEventId++]
);

const rangeOf = async (db, bookingId) => (await db.query(
  `SELECT lower(occupied_range) AS lo, upper(occupied_range) AS hi, venue_id, updated_at
     FROM public.venue_booking WHERE booking_id = $1`,
  [bookingId]
)).rows[0];

const rejectsWith = (promise, code) => assert.rejects(promise, (error) => error.code === code);

const LIVE_LIKE = [
  [1, 1, sgt("08:00", "2026-11-15"), sgt("19:00", "2026-11-15")],
  [110, 2, sgt("09:00"), sgt("17:00"), "PENDING"],
  [114, 3, sgt("09:00", "2026-10-28"), sgt("10:30", "2026-10-28")],
  [116, 3, sgt("11:00", "2026-10-28"), sgt("12:30", "2026-10-28")],
  [172, 4, sgt("09:00", "2027-03-02"), sgt("11:00", "2027-03-02")],
  [173, 4, sgt("09:00", "2027-03-03"), sgt("11:00", "2027-03-03")],
  [900, 2, sgt("09:00"), sgt("17:00"), "REJECTED"],
];

test("[SPM-185] backfill stores ranges from the recorded minutes and leaves updated_at alone", { skip }, async (t) => {
  const db = await setup(t, { bookings: LIVE_LIKE });
  // The SPM-179 backfill already touched updated_at; SPM-185 must not touch it again.
  const editedAt = (await rangeOf(db, 1)).updated_at.toISOString();
  await migrate(db);

  const hall = await rangeOf(db, 1);
  assert.equal(hall.lo.toISOString(), new Date(sgt("07:15", "2026-11-15")).toISOString());
  assert.equal(hall.hi.toISOString(), new Date(sgt("19:45", "2026-11-15")).toISOString());
  assert.equal(hall.updated_at.toISOString(), editedAt);

  const zero = await rangeOf(db, 114);
  assert.equal(zero.lo.toISOString(), new Date(sgt("09:00", "2026-10-28")).toISOString());
  assert.equal(zero.hi.toISOString(), new Date(sgt("10:30", "2026-10-28")).toISOString());

  const fixture = await rangeOf(db, 172);
  assert.equal(fixture.lo, null);
  assert.equal(fixture.venue_id, 68);
  assert.equal((await rangeOf(db, 900)).lo, null, "inactive bookings get no range");
  assert.equal((await db.query("SELECT to_regclass('spm185_venue_minutes') AS t")).rows[0].t, null);
});

test("[SPM-185] backfill re-check stops on overlaps created by setup and turnaround", { skip }, async (t) => {
  // 10:00-12:00 and 12:30-13:00 at venue 45 (30/45) are apart, but not once buffered.
  const db = await setup(t, {
    bookings: [[110, 2, sgt("10:00"), sgt("12:00")], [111, 5, sgt("12:30"), sgt("13:00"), "PENDING"]],
  });

  await assert.rejects(migrate(db), /venue 45: bookings 110 and 111/);
  const applied = await db.query(
    `SELECT (SELECT count(*)::int FROM pg_constraint WHERE conname = 'venue_booking_no_overlap') AS constraints,
            (SELECT count(*)::int FROM pg_proc WHERE proname = 'venue_occupied_range') AS functions`
  );
  assert.deepEqual(applied.rows[0], { constraints: 0, functions: 0 }, "nothing is applied when the re-check fails");
});

test("[SPM-185] backfill re-check ignores overlapping bookings that get no range", { skip }, async (t) => {
  // Fixture venue 68 has no minutes: like live bookings 172 and 173, these two
  // overlap on their windows but get no range, so the constraint ignores them.
  const db = await setup(t, {
    bookings: [[172, 4, sgt("09:00"), sgt("11:00")], [173, 4, sgt("10:00"), sgt("12:00"), "PENDING"]],
  });

  await migrate(db);
  assert.equal((await rangeOf(db, 172)).lo, null);
  assert.equal((await rangeOf(db, 173)).lo, null);
});

test("[SPM-185-TC3] the constraint refuses 13:14 and allows 13:15 after a 10:00-12:00 booking at 30/45", { skip }, async (t) => {
  const db = await setup(t);
  await migrate(db);
  await insertBooking(db, 2, sgt("10:00"), sgt("12:00"), 30, 45, "APPROVED");

  // Room 5 is another room of the same venue: the venue is one bookable space.
  await rejectsWith(insertBooking(db, 5, sgt("13:14"), sgt("14:00"), 30, 45), "23P01");
  await rejectsWith(insertBooking(db, 2, sgt("12:30"), sgt("14:00"), 30, 45), "23P01");
  const allowed = await insertBooking(db, 5, sgt("13:15"), sgt("14:00"), 30, 45);
  assert.equal(allowed.rows[0].venue_id, 45);
});

test("[SPM-185-TC6] a 0/0 venue takes back-to-back bookings and refuses one minute of overlap", { skip }, async (t) => {
  const db = await setup(t);
  await migrate(db);
  await insertBooking(db, 3, sgt("10:00"), sgt("12:00"), 0, 0);

  await insertBooking(db, 3, sgt("12:00"), sgt("14:00"), 0, 0);
  await rejectsWith(insertBooking(db, 3, sgt("11:59"), sgt("12:30"), 0, 0), "23P01");
});

test("[SPM-185-TC7] a two-day booking occupies the venue through the night", { skip }, async (t) => {
  const db = await setup(t);
  await migrate(db);
  await insertBooking(db, 2, sgt("09:00", "2026-11-04"), sgt("18:00", "2026-11-05"), 30, 45);

  await rejectsWith(insertBooking(db, 2, sgt("23:00", "2026-11-04"), sgt("23:30", "2026-11-04"), 30, 45), "23P01");
  await rejectsWith(insertBooking(db, 2, sgt("19:14", "2026-11-05"), sgt("20:00", "2026-11-05"), 30, 45), "23P01");
  await insertBooking(db, 2, sgt("19:15", "2026-11-05"), sgt("20:00", "2026-11-05"), 30, 45);
});

test("[SPM-185-TC10] each venue is checked on its own", { skip }, async (t) => {
  const db = await setup(t);
  await migrate(db);
  await insertBooking(db, 2, sgt("10:00"), sgt("12:00"), 30, 45);

  await insertBooking(db, 1, sgt("10:00"), sgt("12:00"), 45, 45);
  await insertBooking(db, 3, sgt("10:00"), sgt("12:00"), 0, 0);
});

test("[SPM-185] only PENDING and APPROVED bookings occupy the venue; bookings without a range are ignored", { skip }, async (t) => {
  const db = await setup(t, { bookings: [[172, 4, sgt("10:00"), sgt("12:00")]] });
  await migrate(db);
  await insertBooking(db, 2, sgt("10:00"), sgt("12:00"), 30, 45, "REJECTED");
  await insertBooking(db, 2, sgt("10:00"), sgt("12:00"), 30, 45, "CANCELLED");
  await insertBooking(db, 2, sgt("10:00"), sgt("12:00"), 30, 45, "APPROVED");
  // Legacy booking 172 has no range, so it is not compared.
  await insertBooking(db, 4, sgt("10:00"), sgt("12:00"), 0, 0, "APPROVED");

  const reopened = await db.query("SELECT booking_id FROM public.venue_booking WHERE status = 'REJECTED'");
  await rejectsWith(
    db.query("UPDATE public.venue_booking SET status = 'PENDING' WHERE booking_id = $1", [reopened.rows[0].booking_id]),
    "23P01"
  );
});

test("[SPM-185-AC7] two overlapping inserts sent together: one commits, the other gets 23P01", { skip }, async (t) => {
  const db = await setup(t);
  await migrate(db);

  const results = await Promise.allSettled([
    insertBooking(db, 2, sgt("10:00"), sgt("12:00"), 30, 45),
    insertBooking(db, 5, sgt("12:30"), sgt("14:00"), 30, 45),
  ]);

  assert.equal(results.filter((result) => result.status === "fulfilled").length, 1);
  const [refused] = results.filter((result) => result.status === "rejected");
  assert.equal(refused.reason.code, "23P01");
  assert.equal((await db.query("SELECT count(*)::int AS n FROM public.venue_booking")).rows[0].n, 1);
});

test("[SPM-185] venue_occupied_range is half-open, needs both minutes and refuses negative ones", { skip }, async (t) => {
  const db = await setup(t);
  await migrate(db);

  const { rows } = await db.query(
    `SELECT lower(r) AS lo, upper(r) AS hi, lower_inc(r) AS lo_inc, upper_inc(r) AS hi_inc
       FROM (SELECT public.venue_occupied_range($1, $2, 30, 45) AS r) AS x`,
    [sgt("10:00"), sgt("12:00")]
  );
  assert.equal(rows[0].lo.toISOString(), new Date(sgt("09:30")).toISOString());
  assert.equal(rows[0].hi.toISOString(), new Date(sgt("12:45")).toISOString());
  assert.deepEqual([rows[0].lo_inc, rows[0].hi_inc], [true, false]);

  const nullRange = await db.query("SELECT public.venue_occupied_range(now(), now() + interval '1 hour', NULL, 0) AS r");
  assert.equal(nullRange.rows[0].r, null);
  await rejectsWith(db.query("SELECT public.venue_occupied_range(now(), now() + interval '1 hour', -1, 0)"), "22023");
});
