// SPM-270 attendee profile migration on in-memory PostgreSQL (PGlite). No hosted
// database, Auth users or network calls. Runs the migration both on a fresh
// schema and over the table as it was first created in the dashboard. PGlite
// has one connection, so races run in the live integration suite instead.
const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { PGlite } = require(process.env.PGLITE_MODULE || "@electric-sql/pglite");
const root = path.resolve(__dirname, "../..");
const MIGRATION = fs.readFileSync(path.join(root, "supabase/migrations/20261024095646_spm270_attendee_profile.sql"), "utf8");

// The table as found in the development database before this migration.
const DASHBOARD_TABLE = `
  CREATE TABLE public.attendee_profile (
    attendee_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer UNIQUE REFERENCES public."user" (user_id),
    dietary_restrictions text,
    accessibility_requirements text,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
  );
  ALTER TABLE public.attendee_profile ENABLE ROW LEVEL SECURITY;`;

const createDb = async () => {
  const db = new PGlite();
  await db.exec(fs.readFileSync(path.join(root, "tests/fixtures/spm177DatabaseSchema.sql"), "utf8"));
  await db.exec(`
    INSERT INTO public."user" (user_id, email, name, phone, role, is_active) VALUES
      (1, 'attendee-a@spm270.test', 'Attendee A', '+65 8000 0001', 'ATTENDEE', true),
      (2, 'attendee-b@spm270.test', 'Attendee B', NULL, 'ATTENDEE', true),
      (3, 'organiser@spm270.test', 'Organiser', NULL, 'ORGANISER', true),
      (4, 'inactive@spm270.test', 'Inactive Attendee', NULL, 'ATTENDEE', false);`);
  return db;
};

const setup = async ({ dashboardTable = false, beforeMigration = "" } = {}) => {
  const db = await createDb();
  if (dashboardTable) await db.exec(DASHBOARD_TABLE);
  if (beforeMigration) await db.exec(beforeMigration);
  await db.exec(MIGRATION);
  return db;
};

const one = async (db, sql, values = []) => (await db.query(sql, values)).rows[0];
const getProfile = async (db, userId) => (await one(db, "SELECT public.get_attendee_profile($1) AS p", [userId])).p;
const save = async (db, userId, dietary, accessibility, version) =>
  (await one(db, "SELECT public.save_attendee_profile($1, $2, $3, $4) AS r", [userId, dietary, accessibility, version])).r;
const stored = async (db, userId) => one(db, "SELECT * FROM public.attendee_profile WHERE user_id = $1", [userId]);
const columns = async (db) =>
  (await db.query(`
    SELECT column_name, data_type, is_nullable, column_default
      FROM information_schema.columns
     WHERE table_schema = 'public' AND table_name = 'attendee_profile'
     ORDER BY ordinal_position`)).rows;

const EXPECTED_COLUMNS = [
  { column_name: "attendee_id", data_type: "integer", is_nullable: "NO" },
  { column_name: "user_id", data_type: "integer", is_nullable: "NO" },
  { column_name: "dietary_restrictions", data_type: "text", is_nullable: "YES" },
  { column_name: "accessibility_requirements", data_type: "text", is_nullable: "YES" },
  { column_name: "created_at", data_type: "timestamp with time zone", is_nullable: "NO" },
  { column_name: "updated_at", data_type: "timestamp with time zone", is_nullable: "NO" },
  { column_name: "version", data_type: "integer", is_nullable: "NO" },
];

// ---------- drift repair (existing dashboard table) ----------

test("[SPM-270] should_keep_existing_rows_and_align_the_table_when_migrating_the_dashboard_table", async () => {
  const db = await setup({
    dashboardTable: true,
    beforeMigration: "INSERT INTO public.attendee_profile (user_id, dietary_restrictions, created_at, updated_at) VALUES (1, 'Vegan', now(), now());",
  });
  assert.deepEqual(await one(db, "SELECT attendee_id, dietary_restrictions, version FROM public.attendee_profile WHERE user_id = 1"), {
    attendee_id: 1,
    dietary_restrictions: "Vegan",
    version: 1,
  });
  const fk = await one(db, "SELECT pg_get_constraintdef(oid) AS def FROM pg_constraint WHERE conname = 'attendee_profile_user_id_fkey'");
  assert.match(fk.def, /REFERENCES "user"\(user_id\) ON DELETE CASCADE/);
  // The kept row continues as version 1 and can be saved with it.
  assert.equal((await save(db, 1, "Vegan", "Ramp", 1)).profile.version, 2);
});

test("[SPM-270] should_give_the_same_shape_when_migrating_a_fresh_schema_or_the_dashboard_table", async () => {
  const fresh = await setup();
  const repaired = await setup({ dashboardTable: true });
  const shape = (rows) => rows.map(({ column_default, ...rest }) => rest);
  assert.deepEqual(shape(await columns(fresh)), EXPECTED_COLUMNS);
  assert.deepEqual(shape(await columns(repaired)), EXPECTED_COLUMNS);
  const defaults = Object.fromEntries((await columns(repaired)).map((c) => [c.column_name, c.column_default]));
  assert.equal(defaults.created_at, "now()");
  assert.equal(defaults.updated_at, "now()");
  assert.equal(defaults.version, "1");
  const constraintNames = async (db) =>
    (await db.query("SELECT conname FROM pg_constraint WHERE conrelid = 'public.attendee_profile'::regclass ORDER BY conname")).rows.map((r) => r.conname);
  assert.deepEqual(await constraintNames(repaired), await constraintNames(fresh));
});

for (const [label, row, pattern] of [
  ["a profile without a user", "INSERT INTO public.attendee_profile (user_id, created_at, updated_at) VALUES (NULL, now(), now());", /null values|contains null/],
  ["blank dietary text", "INSERT INTO public.attendee_profile (user_id, dietary_restrictions, created_at, updated_at) VALUES (1, '   ', now(), now());", /dietary_restrictions_check/],
  ["over-long accessibility text", `INSERT INTO public.attendee_profile (user_id, accessibility_requirements, created_at, updated_at) VALUES (1, repeat('x', 1001), now(), now());`, /accessibility_requirements_check/],
]) {
  test(`[SPM-270] should_fail_without_changing_anything_when_the_dashboard_table_holds_${label.replace(/ /g, "_")}`, async () => {
    const db = await createDb();
    await db.exec(DASHBOARD_TABLE);
    await db.exec(row);
    await assert.rejects(db.exec(MIGRATION), pattern);
    await db.exec("ROLLBACK");
    const names = (await columns(db)).map((c) => c.column_name);
    assert.ok(!names.includes("version"), "the failed migration must not leave a partial change");
    assert.equal((await one(db, "SELECT count(*)::int AS n FROM pg_proc WHERE proname = 'save_attendee_profile'")).n, 0);
    assert.equal((await one(db, "SELECT count(*)::int AS n FROM public.attendee_profile")).n, 1);
  });
}

// Master 6.3: only ATTENDEE users may hold a profile. A row that broke the rule
// before the trigger existed must not survive the migration.
test("[SPM-270] should_not_leave_a_non_attendee_profile_when_the_dashboard_table_already_holds_one", async () => {
  const db = await createDb();
  await db.exec(DASHBOARD_TABLE);
  await db.exec("INSERT INTO public.attendee_profile (user_id, created_at, updated_at) VALUES (3, now(), now());");
  let migrated = true;
  try {
    await db.exec(MIGRATION);
  } catch {
    migrated = false;
    await db.exec("ROLLBACK");
  }
  const offending = (await one(db, `
    SELECT count(*)::int AS n FROM public.attendee_profile p
      JOIN public."user" u USING (user_id) WHERE u.role <> 'ATTENDEE'`)).n;
  assert.ok(!migrated || offending === 0, `migration succeeded but left ${offending} profile(s) owned by a non-attendee`);
});

// ---------- behaviour after migration, on both paths ----------

for (const dashboardTable of [false, true]) {
  const label = dashboardTable ? "existing_table" : "fresh_schema";

  test(`[TC-PROFILE-001] should_return_user_details_and_null_profile_fields_when_no_profile_is_saved_${label}`, async () => {
    const db = await setup({ dashboardTable });
    const before = await getProfile(db, 1);
    assert.deepEqual(before, {
      attendee_id: null,
      user_id: 1,
      name: "Attendee A",
      email: "attendee-a@spm270.test",
      phone: "+65 8000 0001",
      dietary_restrictions: null,
      accessibility_requirements: null,
      version: null,
      created_at: null,
      updated_at: null,
    });
  });

  test(`[TC-PROFILE-004] should_create_one_profile_linked_to_the_user_when_the_first_save_has_no_version_${label}`, async () => {
    const db = await setup({ dashboardTable });
    const created = await save(db, 1, "Vegetarian", null, null);
    assert.equal(created.created, true);
    assert.equal(created.profile.user_id, 1);
    assert.equal(created.profile.version, 1);
    assert.equal(created.profile.dietary_restrictions, "Vegetarian");
    assert.equal((await one(db, "SELECT count(*)::int AS n FROM public.attendee_profile WHERE user_id = 1")).n, 1);
  });

  test(`[TC-PROFILE-006] should_update_fields_bump_the_version_and_touch_updated_at_when_the_version_matches_${label}`, async () => {
    const db = await setup({ dashboardTable });
    await save(db, 1, "Vegetarian", null, null);
    await db.query("UPDATE public.attendee_profile SET created_at = now() - interval '1 day', updated_at = now() - interval '1 day' WHERE user_id = 1");
    const before = await stored(db, 1);
    const updated = await save(db, 1, null, "Step-free access", 1);
    const after = await stored(db, 1);
    assert.equal(updated.created, false);
    assert.equal(after.version, 2);
    assert.equal(after.attendee_id, before.attendee_id);
    assert.equal(after.dietary_restrictions, null);
    assert.equal(after.accessibility_requirements, "Step-free access");
    assert.equal(after.created_at.getTime(), before.created_at.getTime());
    assert.ok(after.updated_at > before.updated_at);
  });

  test(`[TC-PROFILE-005] should_refuse_with_stale_profile_and_write_nothing_when_a_create_or_version_is_stale_${label}`, async () => {
    const db = await setup({ dashboardTable });
    await save(db, 1, "Halal", null, null);
    const before = await stored(db, 1);
    await assert.rejects(save(db, 1, "Kosher", null, null), /STALE_PROFILE/);
    await assert.rejects(save(db, 1, "Kosher", null, 7), /STALE_PROFILE/);
    await assert.rejects(save(db, 2, "Kosher", null, 1), /STALE_PROFILE/);
    assert.deepEqual(await stored(db, 1), before);
    assert.equal(await stored(db, 2), undefined);
  });

  test(`[TC-PROFILE-003] should_refuse_with_not_attendee_when_the_user_is_not_an_active_attendee_${label}`, async () => {
    const db = await setup({ dashboardTable });
    for (const userId of [3, 4, 999]) {
      await assert.rejects(save(db, userId, "Vegan", null, null), /NOT_ATTENDEE/);
      assert.equal(await getProfile(db, userId), null);
    }
    assert.equal((await one(db, "SELECT count(*)::int AS n FROM public.attendee_profile")).n, 0);
  });

  test(`[TC-PROFILE-003] should_refuse_saves_and_hide_the_profile_when_its_owner_is_deactivated_${label}`, async () => {
    const db = await setup({ dashboardTable });
    await save(db, 1, "Vegan", null, null);
    await db.query('UPDATE public."user" SET is_active = false WHERE user_id = 1');
    await assert.rejects(save(db, 1, "Halal", null, 1), /NOT_ATTENDEE/);
    assert.equal(await getProfile(db, 1), null);
    assert.equal((await stored(db, 1)).dietary_restrictions, "Vegan");
  });

  test(`[SPM-270-AC4] should_block_non_attendee_owners_when_writes_bypass_the_function_${label}`, async () => {
    const db = await setup({ dashboardTable });
    await assert.rejects(db.query("INSERT INTO public.attendee_profile (user_id) VALUES (3)"), /NOT_ATTENDEE/);
    await save(db, 1, null, null, null);
    await assert.rejects(db.query("UPDATE public.attendee_profile SET user_id = 3 WHERE user_id = 1"), /NOT_ATTENDEE/);
  });

  test(`[TC-PROFILE-005] should_refuse_a_second_profile_for_the_same_user_when_inserted_directly_${label}`, async () => {
    const db = await setup({ dashboardTable });
    await db.query("INSERT INTO public.attendee_profile (user_id) VALUES (1)");
    await assert.rejects(db.query("INSERT INTO public.attendee_profile (user_id) VALUES (1)"), (error) => error.code === "23505");
    await assert.rejects(db.query("INSERT INTO public.attendee_profile (user_id) VALUES (NULL)"), /NOT_ATTENDEE|null value/);
  });

  test(`[TC-PROFILE-010] should_roll_back_the_whole_save_when_a_value_breaks_a_constraint_${label}`, async () => {
    const db = await setup({ dashboardTable });
    await assert.rejects(save(db, 2, "   ", null, null), (error) => error.code === "23514");
    assert.equal(await stored(db, 2), undefined);
    await save(db, 2, "Halal", null, null);
    await assert.rejects(save(db, 2, null, "x".repeat(1001), 1), (error) => error.code === "23514");
    const after = await stored(db, 2);
    assert.equal(after.version, 1);
    assert.equal(after.dietary_restrictions, "Halal");
    assert.equal((await save(db, 2, "x".repeat(1000), null, 1)).profile.version, 2);
  });

  test(`[SPM-270] should_remove_only_that_users_profile_when_a_user_is_deleted_${label}`, async () => {
    const db = await setup({ dashboardTable });
    await save(db, 1, "Vegan", null, null);
    await save(db, 2, "Halal", null, null);
    await db.query('DELETE FROM public."user" WHERE user_id = 1');
    assert.deepEqual((await db.query("SELECT user_id FROM public.attendee_profile ORDER BY user_id")).rows, [{ user_id: 2 }]);
  });

  test(`[SPM-270] should_reach_the_table_only_through_the_functions_when_using_runtime_roles_${label}`, async () => {
    const db = await setup({ dashboardTable });
    assert.deepEqual(await one(db, `
      SELECT
        has_table_privilege('service_role', 'public.attendee_profile', 'SELECT, INSERT, UPDATE, DELETE, TRUNCATE') AS service_table,
        has_table_privilege('anon', 'public.attendee_profile', 'SELECT') AS anon_table,
        has_table_privilege('authenticated', 'public.attendee_profile', 'SELECT') AS auth_table,
        has_function_privilege('service_role', 'public.get_attendee_profile(integer)', 'EXECUTE') AS service_get,
        has_function_privilege('service_role', 'public.save_attendee_profile(integer, text, text, integer)', 'EXECUTE') AS service_save,
        has_function_privilege('anon', 'public.save_attendee_profile(integer, text, text, integer)', 'EXECUTE') AS anon_save,
        has_function_privilege('authenticated', 'public.get_attendee_profile(integer)', 'EXECUTE') AS auth_get,
        (SELECT relrowsecurity FROM pg_class WHERE oid = 'public.attendee_profile'::regclass) AS rls`), {
      service_table: false,
      anon_table: false,
      auth_table: false,
      service_get: true,
      service_save: true,
      anon_save: false,
      auth_get: false,
      rls: true,
    });
  });
}
