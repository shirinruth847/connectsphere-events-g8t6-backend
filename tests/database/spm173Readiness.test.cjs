// SPM-173 interim readiness (Master 5.3) on in-memory PostgreSQL. These tests
// never connect to hosted Supabase. The reduced SPM-177 schema has no booking,
// equipment request or change request tables, so minimal copies of the live
// columns the readiness check reads are added here.
const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { PGlite } = require(process.env.PGLITE_MODULE || "@electric-sql/pglite");
const root = path.resolve(__dirname, "../..");
const migration = (name) => fs.readFileSync(path.join(root, "supabase/migrations", name), "utf8");

async function setup() {
  const db = new PGlite();
  await db.exec(fs.readFileSync(path.join(root, "tests/fixtures/spm177DatabaseSchema.sql"), "utf8"));
  await db.exec(`
    CREATE TYPE public.booking_status AS ENUM ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED');
    CREATE TYPE public.equipment_request_status AS ENUM ('PENDING', 'APPROVED', 'REJECTED', 'PARTIALLY_FULFILLED');
    CREATE TYPE public.change_request_status AS ENUM ('PENDING', 'APPROVED', 'REJECTED');
    CREATE TABLE public.venue_booking (
      booking_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      room_id integer NOT NULL REFERENCES public.room (room_id),
      event_id integer NOT NULL REFERENCES public.event (event_id),
      start_datetime timestamptz NOT NULL,
      end_datetime timestamptz NOT NULL,
      status public.booking_status NOT NULL DEFAULT 'PENDING',
      expected_attendance integer
    );
    CREATE TABLE public.equipment_request (
      equip_request_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      equipment_id integer NOT NULL REFERENCES public.equipment (equipment_id),
      event_id integer NOT NULL REFERENCES public.event (event_id),
      status public.equipment_request_status NOT NULL DEFAULT 'PENDING'
    );
    CREATE TABLE public.event_change_request (
      change_request_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      event_id integer NOT NULL REFERENCES public.event (event_id),
      status public.change_request_status NOT NULL DEFAULT 'PENDING'
    );
    CREATE TABLE public.resource_incidents (
      incident_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      event_id integer NOT NULL REFERENCES public.event (event_id),
      status text NOT NULL CHECK (status IN ('OPEN', 'RESOLVED'))
    );
  `);
  await db.exec(migration("20261020112025_spm173_interim_readiness.sql"));
  await db.exec(migration("20261020142915_spm173_readiness_without_venue_buffer.sql"));
  await db.exec(migration("20261021100000_spm173_fail_closed_incident_readiness.sql"));
  await db.exec(`
    INSERT INTO public."user" (user_id, email, name, role, is_active) VALUES (1, 'spm173-owner@example.test', 'Owner', 'ORGANISER', true);
    INSERT INTO public.venue (venue_id, name, address, max_capacity, setup_turnaround_min) VALUES
      (1, 'Hall', '1 Test Road', 200, 30),
      (2, 'Annex', '2 Test Road', 500, 0);
    INSERT INTO public.room (room_id, venue_id, layout_type, capacity) VALUES
      (1, 1, 'THEATRE', 200), (2, 1, 'BANQUET', 200), (3, 2, 'THEATRE', 500);
    INSERT INTO public.equipment (equipment_id, name, category) VALUES (1, 'Projector', 'AV'), (2, 'Microphone', 'AV');
  `);
  return db;
}

let nextEvent = 0;
// An event in PLANNING with its own day, plus the bookings, technical rows and
// change requests the case needs.
async function event(db, { attendance = 50, registration = null, bookings = [], needs = [], requests = [], changeRequests = [] } = {}) {
  nextEvent += 1;
  const day = `2030-02-${String(nextEvent).padStart(2, "0")}`;
  const start = `${day}T09:00:00Z`;
  const end = `${day}T11:00:00Z`;
  const { rows } = await db.query(
    `INSERT INTO public.event (organiser_id, title, status, start_datetime, end_datetime, expected_attendance,
       is_registration_enabled, registration_capacity, is_published)
     VALUES (1, $1, 'PLANNING', $2, $3, $4, $5, $6, true) RETURNING event_id`,
    [`spm173 readiness ${nextEvent}`, start, end, attendance, registration !== null, registration]
  );
  const eventId = rows[0].event_id;
  for (const booking of bookings) {
    await db.query(
      "INSERT INTO public.venue_booking (room_id, event_id, start_datetime, end_datetime, status, expected_attendance) VALUES ($1, $2, $3, $4, $5, $6)",
      [booking.room ?? 1, eventId, booking.start ?? start, booking.end ?? end, booking.status ?? "APPROVED", booking.attendance ?? null]
    );
  }
  for (const equipmentId of needs) {
    await db.query("INSERT INTO public.event_equipment_requirement (event_id, equipment_id, quantity_requested) VALUES ($1, $2, 1)", [eventId, equipmentId]);
  }
  for (const [equipmentId, status] of requests) {
    await db.query("INSERT INTO public.equipment_request (equipment_id, event_id, status) VALUES ($1, $2, $3)", [equipmentId, eventId, status]);
  }
  for (const status of changeRequests) {
    await db.query("INSERT INTO public.event_change_request (event_id, status) VALUES ($1, $2)", [eventId, status]);
  }
  return { eventId, start, end, day };
}

const readiness = async (db, eventId) => (await db.query("SELECT public._event_readiness($1) AS codes", [eventId])).rows[0].codes;

test("an event with one approved booking and no technical needs is ready", async () => {
  const db = await setup();
  const { eventId } = await event(db, { bookings: [{}] });
  assert.deepEqual(await readiness(db, eventId), []);
});

test("bookings: none, pending, rejected or cancelled ones, and capacity", async () => {
  const db = await setup();
  assert.deepEqual(await readiness(db, (await event(db)).eventId), ["NO_ACTIVE_BOOKING"]);
  assert.deepEqual(await readiness(db, (await event(db, { bookings: [{ status: "PENDING" }] })).eventId), ["BOOKING_NOT_APPROVED"]);
  // Rejected and cancelled bookings never count, so they neither help nor block.
  const withHistory = await event(db, { bookings: [{}, { room: 3, status: "REJECTED" }, { room: 3, status: "CANCELLED" }] });
  assert.deepEqual(await readiness(db, withHistory.eventId), []);
  assert.deepEqual(await readiness(db, (await event(db, { bookings: [{ status: "REJECTED" }] })).eventId), ["NO_ACTIVE_BOOKING"]);
  // The booking's own attendance, else the event's, against the venue's capacity.
  assert.deepEqual(await readiness(db, (await event(db, { bookings: [{ attendance: 201 }] })).eventId), ["BOOKING_OVER_CAPACITY"]);
  assert.deepEqual(await readiness(db, (await event(db, { attendance: 250, bookings: [{}] })).eventId), ["BOOKING_OVER_CAPACITY"]);
  assert.deepEqual(await readiness(db, (await event(db, { attendance: 250, bookings: [{ attendance: 150 }] })).eventId), []);
});

test("another active booking at the same venue over an overlapping window is a conflict", async () => {
  const db = await setup();
  const first = await event(db, { bookings: [{}] });
  // Another room of the same venue, overlapping the first booking's last half hour.
  const overlapping = await event(db, { bookings: [{ room: 2, status: "PENDING", start: `${first.day}T10:30:00Z`, end: `${first.day}T12:00:00Z` }] });
  assert.deepEqual(await readiness(db, first.eventId), ["BOOKING_CONFLICT"]);
  // A pending booking occupies the venue too; a rejected one does not.
  await db.query("UPDATE public.venue_booking SET status = 'REJECTED' WHERE event_id = $1", [overlapping.eventId]);
  assert.deepEqual(await readiness(db, first.eventId), []);
  // Back to back is not a conflict, and the deprecated setup_turnaround_min
  // (30 minutes on this venue) is no longer read (Master 1.2 section 6.2).
  const next = await event(db, { bookings: [{ room: 2, start: `${first.day}T11:00:00Z`, end: `${first.day}T12:00:00Z` }] });
  assert.deepEqual(await readiness(db, next.eventId), []);
  assert.deepEqual(await readiness(db, first.eventId), []);
});

test("the primary venue is the only active booking until the primary flag exists", async () => {
  const db = await setup();
  const twoVenues = await event(db, { bookings: [{}, { room: 3 }] });
  assert.deepEqual(await readiness(db, twoVenues.eventId), ["NO_PRIMARY_VENUE"]);
  const primary = await db.query("SELECT * FROM public._event_primary_venue($1)", [(await event(db, { bookings: [{ room: 3 }] })).eventId]);
  assert.deepEqual(primary.rows, [{ venue_id: 2, name: "Annex", address: "2 Test Road", max_capacity: 500 }]);
});

test("technical needs must each have an approved request", async () => {
  const db = await setup();
  const codes = async (options) => readiness(db, (await event(db, { bookings: [{}], ...options })).eventId);
  assert.deepEqual(await codes({ needs: [1] }), ["TECHNICAL_NOT_APPROVED"]);
  assert.deepEqual(await codes({ needs: [1], requests: [[1, "APPROVED"]] }), []);
  assert.deepEqual(await codes({ needs: [1, 2], requests: [[1, "APPROVED"]] }), ["TECHNICAL_NOT_APPROVED"]);
  assert.deepEqual(await codes({ needs: [1], requests: [[1, "REJECTED"]] }), ["TECHNICAL_NOT_APPROVED"]);
  assert.deepEqual(await codes({ requests: [[1, "PENDING"]] }), ["TECHNICAL_NOT_APPROVED"]);
  assert.deepEqual(await codes({ requests: [[1, "PARTIALLY_FULFILLED"]] }), ["TECHNICAL_NOT_APPROVED"]);
  // A rejected request with no remaining need leaves nothing to approve (NOT_REQUIRED).
  assert.deepEqual(await codes({ requests: [[1, "REJECTED"]] }), []);
});

test("registration settings and open change requests", async () => {
  const db = await setup();
  const codes = async (options) => readiness(db, (await event(db, { bookings: [{}], ...options })).eventId);
  assert.deepEqual(await codes({ registration: 200 }), []);
  assert.deepEqual(await codes({ registration: 201 }), ["REGISTRATION_EXCEEDS_PRIMARY_CAPACITY"]);
  assert.deepEqual(await codes({ registration: 0 }), ["REGISTRATION_INVALID"]);
  assert.deepEqual(await codes({ changeRequests: ["PENDING"] }), ["OPEN_CHANGE_REQUEST"]);
  assert.deepEqual(await codes({ changeRequests: ["APPROVED", "REJECTED"] }), []);
});

test("an open resource incident blocks readiness", async () => {
  const db = await setup();
  const { eventId } = await event(db, { bookings: [{}] });
  await db.query("INSERT INTO public.resource_incidents (event_id, status) VALUES ($1, 'OPEN')", [eventId]);
  assert.deepEqual(await readiness(db, eventId), ["OPEN_BLOCKING_INCIDENT"]);
});

test("readiness fails closed while the incident schema is unavailable", async () => {
  const db = await setup();
  const { eventId } = await event(db, { bookings: [{}] });
  await db.exec("DROP TABLE public.resource_incidents");
  assert.deepEqual(await readiness(db, eventId), ["READINESS_DATA_PENDING"]);
});

test("an unknown event is refused", async () => {
  const db = await setup();
  await assert.rejects(readiness(db, 999), /EVENT_NOT_FOUND/);
});

test("the attendee snapshot names the primary venue", async () => {
  const db = await setup();
  const { eventId } = await event(db, { bookings: [{}] });
  const { rows } = await db.query("SELECT public._event_attendee_snapshot(e) AS snapshot FROM public.event e WHERE event_id = $1", [eventId]);
  assert.deepEqual(rows[0].snapshot.primary_venue, { venue_id: 1, name: "Hall", address: "1 Test Road" });
  assert.equal(rows[0].snapshot.is_published, true);
});
