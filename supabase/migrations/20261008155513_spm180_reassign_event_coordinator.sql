-- SPM-180: preserve assignment history and reassign atomically.
CREATE TABLE public.event_assignments (
  assignment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id integer NOT NULL REFERENCES public.event (event_id),
  coordinator_id integer NOT NULL REFERENCES public."user" (user_id),
  assigned_by integer REFERENCES public."user" (user_id),
  assigned_at timestamptz NOT NULL DEFAULT now(),
  ended_at timestamptz,
  reason text,
  CONSTRAINT event_assignments_time_order_check
    CHECK (ended_at IS NULL OR ended_at >= assigned_at)
);

CREATE UNIQUE INDEX event_assignments_one_active_per_event
  ON public.event_assignments (event_id)
  WHERE ended_at IS NULL;
CREATE INDEX event_assignments_coordinator_history
  ON public.event_assignments (coordinator_id, assigned_at DESC);

ALTER TABLE public.event_assignments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.event_assignments FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.event_assignments TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.event_assignments_assignment_id_seq TO service_role;

-- Historical assignment timestamps and assigning Leads were not recorded by
-- the legacy schema. Seed a baseline at migration time without inventing them.
INSERT INTO public.event_assignments (event_id, coordinator_id, assigned_at, reason)
SELECT event_id, coordinator_id, now(), 'LEGACY_BASELINE'
  FROM public.event
 WHERE coordinator_id IS NOT NULL;

-- The Lead queue is part of the assignment workflow used to create the first
-- coordinator assignment before later reassignment.
CREATE OR REPLACE FUNCTION public.assign_event_coordinator(
  p_event_id integer,
  p_coordinator_id integer,
  p_lead_id integer
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_event public.event;
  v_coordinator public."user";
  v_notification_id integer;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public."user"
     WHERE user_id = p_lead_id
       AND role = 'COORDINATOR_LEAD'
       AND is_active
  ) THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'FORBIDDEN';
  END IF;

  SELECT * INTO v_event
    FROM public.event
   WHERE event_id = p_event_id
     AND status = 'SUBMITTED'
     AND coordinator_id IS NULL
   FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'P0002', MESSAGE = 'EVENT_NOT_FOUND';
  END IF;

  SELECT * INTO v_coordinator
    FROM public."user"
   WHERE user_id = p_coordinator_id
     AND role = 'COORDINATOR'
     AND is_active
   FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'INVALID_COORDINATOR';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.event AS other_event
     WHERE other_event.coordinator_id = p_coordinator_id
       AND other_event.status NOT IN ('DRAFT', 'COMPLETED', 'REJECTED', 'CANCELLED')
       AND other_event.start_datetime < v_event.end_datetime
       AND other_event.end_datetime > v_event.start_datetime
  ) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'COORDINATOR_CONFLICT';
  END IF;

  UPDATE public.event
     SET coordinator_id = p_coordinator_id, updated_at = now()
   WHERE event_id = p_event_id
     AND coordinator_id IS NULL
   RETURNING * INTO v_event;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'P0002', MESSAGE = 'EVENT_NOT_FOUND';
  END IF;

  INSERT INTO public.event_assignments (event_id, coordinator_id, assigned_by)
  VALUES (p_event_id, p_coordinator_id, p_lead_id);

  INSERT INTO public.notification (event_id, title, message, type)
  VALUES (p_event_id, 'Event coordinator assigned',
    format('Coordinator %s has been assigned to your event request REQ-%s.',
      v_coordinator.name, lpad(p_event_id::text, 6, '0')), 'STATUS_CHANGE')
  RETURNING notification_id INTO v_notification_id;
  INSERT INTO public.notification_recipient (notification_id, recipient_id)
  VALUES (v_notification_id, v_event.organiser_id);

  INSERT INTO public.notification (event_id, title, message, type)
  VALUES (p_event_id, 'New event coordination assignment',
    format('You have been assigned to coordinate event request REQ-%s: %s.',
      lpad(p_event_id::text, 6, '0'), v_event.title), 'STATUS_CHANGE')
  RETURNING notification_id INTO v_notification_id;
  INSERT INTO public.notification_recipient (notification_id, recipient_id)
  VALUES (v_notification_id, p_coordinator_id);

  RETURN jsonb_build_object('event', to_jsonb(v_event));
END;
$$;

REVOKE ALL ON FUNCTION public.assign_event_coordinator(integer, integer, integer)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.assign_event_coordinator(integer, integer, integer)
  TO service_role;

CREATE OR REPLACE FUNCTION public.reassign_event_coordinator(
  p_event_id integer,
  p_coordinator_id integer,
  p_expected_coordinator_id integer,
  p_lead_id integer
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_event public.event;
  v_old_coordinator public."user";
  v_coordinator public."user";
  v_notification_id integer;
BEGIN
  IF NOT EXISTS (
    SELECT 1
      FROM public."user"
     WHERE user_id = p_lead_id
       AND role = 'COORDINATOR_LEAD'
       AND is_active
  ) THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'FORBIDDEN';
  END IF;

  SELECT *
    INTO v_event
    FROM public.event
   WHERE event_id = p_event_id
     AND coordinator_id IS NOT NULL
     AND status NOT IN ('COMPLETED', 'CANCELLED', 'REJECTED')
   FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'P0002', MESSAGE = 'EVENT_NOT_REASSIGNABLE';
  END IF;

  IF v_event.coordinator_id IS DISTINCT FROM p_expected_coordinator_id THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'ASSIGNMENT_CHANGED';
  END IF;

  IF v_event.coordinator_id = p_coordinator_id THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'COORDINATOR_UNCHANGED';
  END IF;

  SELECT *
    INTO v_old_coordinator
    FROM public."user"
   WHERE user_id = v_event.coordinator_id;

  -- Ensure only the supervising Lead can reassign this event.
  PERFORM 1
    FROM public.event_assignments
   WHERE event_id = p_event_id
     AND ended_at IS NULL
     AND assigned_by = p_lead_id
    FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'FORBIDDEN';
  END IF;

  -- Serializes assignments to this coordinator so overlapping events cannot
  -- both pass the availability check concurrently.
  SELECT *
    INTO v_coordinator
    FROM public."user"
   WHERE user_id = p_coordinator_id
     AND role = 'COORDINATOR'
     AND is_active
   FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'INVALID_COORDINATOR';
  END IF;

  IF EXISTS (
    SELECT 1
      FROM public.event AS other_event
     WHERE other_event.coordinator_id = p_coordinator_id
       AND other_event.event_id <> p_event_id
       AND other_event.status NOT IN ('DRAFT', 'COMPLETED', 'CANCELLED', 'REJECTED')
       AND other_event.start_datetime < v_event.end_datetime
       AND other_event.end_datetime > v_event.start_datetime
  ) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'COORDINATOR_CONFLICT';
  END IF;

  UPDATE public.event_assignments
     SET ended_at = now()
   WHERE event_id = p_event_id
     AND ended_at IS NULL;

  UPDATE public.event
     SET coordinator_id = p_coordinator_id,
         updated_at = now()
   WHERE event_id = p_event_id
   RETURNING * INTO v_event;

  INSERT INTO public.event_assignments (event_id, coordinator_id, assigned_by)
  VALUES (p_event_id, p_coordinator_id, p_lead_id);

  INSERT INTO public.activity_log (user_id, entity_name, entity_id, action, details)
  VALUES (
    p_lead_id,
    'event',
    p_event_id,
    'COORDINATOR_REASSIGNED',
    jsonb_build_object(
      'previousCoordinatorId', v_old_coordinator.user_id,
      'coordinatorId', p_coordinator_id
    )::text
  );

  INSERT INTO public.notification (event_id, title, message, type)
  VALUES (
    p_event_id,
    'Event coordinator changed',
    format('The coordinator for event request REQ-%s has changed.', lpad(p_event_id::text, 6, '0')),
    'STATUS_CHANGE'
  )
  RETURNING notification_id INTO v_notification_id;
  INSERT INTO public.notification_recipient (notification_id, recipient_id)
  VALUES (v_notification_id, v_event.organiser_id);

  INSERT INTO public.notification (event_id, title, message, type)
  VALUES (
    p_event_id,
    'Event assignment ended',
    format('Your coordinator assignment for event request REQ-%s has ended.', lpad(p_event_id::text, 6, '0')),
    'STATUS_CHANGE'
  )
  RETURNING notification_id INTO v_notification_id;
  INSERT INTO public.notification_recipient (notification_id, recipient_id)
  VALUES (v_notification_id, v_old_coordinator.user_id);

  INSERT INTO public.notification (event_id, title, message, type)
  VALUES (
    p_event_id,
    'New event coordination assignment',
    format('You have been assigned to coordinate event request REQ-%s: %s.', lpad(p_event_id::text, 6, '0'), v_event.title),
    'STATUS_CHANGE'
  )
  RETURNING notification_id INTO v_notification_id;
  INSERT INTO public.notification_recipient (notification_id, recipient_id)
  VALUES (v_notification_id, p_coordinator_id);

  RETURN jsonb_build_object(
    'event', jsonb_build_object(
      'event_id', v_event.event_id,
      'title', v_event.title,
      'status', v_event.status,
      'coordinator_id', v_event.coordinator_id
    ),
    'coordinator', jsonb_build_object(
      'user_id', v_coordinator.user_id,
      'name', v_coordinator.name
    )
  );
END;
$$;

REVOKE ALL ON FUNCTION public.reassign_event_coordinator(integer, integer, integer, integer)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.reassign_event_coordinator(integer, integer, integer, integer)
  TO service_role;
