-- SPM-270 Attendee Profile.
--   * The development database already had attendee_profile, created outside
--     the migration history (no rows on 2026-10-24). This migration is the
--     repository definition: it creates the table where it is missing and
--     aligns the existing one in place, keeping any rows.
--   * Name, email and phone stay on "user"; the profile holds only the
--     attendee's dietary and accessibility information.
--   * One profile per user (UNIQUE user_id), only for ATTENDEE users
--     (trigger), versioned so a stale save is refused (Master 6.1).
--   * The profile is the user's personal data, so it goes with the user row
--     (ON DELETE CASCADE, like idempotency_records).
--   * The backend reaches the table only through the two functions below.

BEGIN;

CREATE TABLE IF NOT EXISTS public.attendee_profile (
  attendee_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL CONSTRAINT attendee_profile_user_id_key UNIQUE,
  dietary_restrictions text,
  accessibility_requirements text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.attendee_profile
  ALTER COLUMN user_id SET NOT NULL,
  ALTER COLUMN created_at SET DEFAULT now(),
  ALTER COLUMN updated_at SET DEFAULT now(),
  ADD COLUMN version integer NOT NULL DEFAULT 1,
  ADD CONSTRAINT attendee_profile_version_check CHECK (version > 0),
  ADD CONSTRAINT attendee_profile_dietary_restrictions_check
    CHECK (dietary_restrictions IS NULL OR (btrim(dietary_restrictions) <> '' AND char_length(dietary_restrictions) <= 1000)),
  ADD CONSTRAINT attendee_profile_accessibility_requirements_check
    CHECK (accessibility_requirements IS NULL OR (btrim(accessibility_requirements) <> '' AND char_length(accessibility_requirements) <= 1000));

ALTER TABLE public.attendee_profile DROP CONSTRAINT IF EXISTS attendee_profile_user_id_fkey;
ALTER TABLE public.attendee_profile
  ADD CONSTRAINT attendee_profile_user_id_fkey
  FOREIGN KEY (user_id) REFERENCES public."user" (user_id) ON DELETE CASCADE;

-- A plain foreign key cannot say which users may own a profile. FOR SHARE
-- holds the role until commit, so a concurrent role change waits.
CREATE FUNCTION public._attendee_profile_requires_attendee()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
  PERFORM 1 FROM public."user" WHERE user_id = NEW.user_id AND role = 'ATTENDEE' FOR SHARE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'NOT_ATTENDEE';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER attendee_profile_requires_attendee
  BEFORE INSERT OR UPDATE OF user_id ON public.attendee_profile
  FOR EACH ROW EXECUTE FUNCTION public._attendee_profile_requires_attendee();

CREATE FUNCTION public._touch_attendee_profile_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER attendee_profile_touch_updated_at
  BEFORE UPDATE ON public.attendee_profile
  FOR EACH ROW EXECUTE FUNCTION public._touch_attendee_profile_updated_at();

-- The attendee's contact details and profile, or NULL when the user is not an
-- active ATTENDEE. Before the first save the profile fields are NULL. Event
-- Registration reads attendee details through this function too (AC10).
CREATE FUNCTION public.get_attendee_profile(p_user_id integer)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT jsonb_build_object(
    'attendee_id', p.attendee_id,
    'user_id', u.user_id,
    'name', u.name,
    'email', u.email,
    'phone', u.phone,
    'dietary_restrictions', p.dietary_restrictions,
    'accessibility_requirements', p.accessibility_requirements,
    'version', p.version,
    'created_at', p.created_at,
    'updated_at', p.updated_at
  )
  FROM public."user" AS u
  LEFT JOIN public.attendee_profile AS p ON p.user_id = u.user_id
  WHERE u.user_id = p_user_id AND u.role = 'ATTENDEE' AND u.is_active;
$$;

-- Creates the profile when p_expected_version is NULL and updates it when the
-- version matches. A create over an existing profile, or an update with any
-- other version, is STALE_PROFILE: the caller saved over data it had not seen.
-- The single conditional statement settles simultaneous first saves.
CREATE FUNCTION public.save_attendee_profile(
  p_user_id integer,
  p_dietary_restrictions text,
  p_accessibility_requirements text,
  p_expected_version integer
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_rows integer;
BEGIN
  PERFORM 1 FROM public."user"
   WHERE user_id = p_user_id AND role = 'ATTENDEE' AND is_active
   FOR SHARE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'NOT_ATTENDEE';
  END IF;

  IF p_expected_version IS NULL THEN
    INSERT INTO public.attendee_profile (user_id, dietary_restrictions, accessibility_requirements)
    VALUES (p_user_id, p_dietary_restrictions, p_accessibility_requirements)
    ON CONFLICT (user_id) DO NOTHING;
  ELSE
    UPDATE public.attendee_profile
       SET dietary_restrictions = p_dietary_restrictions,
           accessibility_requirements = p_accessibility_requirements,
           version = version + 1
     WHERE user_id = p_user_id AND version = p_expected_version;
  END IF;

  GET DIAGNOSTICS v_rows = ROW_COUNT;
  IF v_rows = 0 THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'STALE_PROFILE';
  END IF;

  RETURN jsonb_build_object(
    'created', p_expected_version IS NULL,
    'profile', public.get_attendee_profile(p_user_id)
  );
END;
$$;

ALTER TABLE public.attendee_profile ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.attendee_profile FROM PUBLIC, anon, authenticated, service_role;

REVOKE ALL ON FUNCTION public._attendee_profile_requires_attendee() FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON FUNCTION public._touch_attendee_profile_updated_at() FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON FUNCTION public.get_attendee_profile(integer) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.save_attendee_profile(integer, text, text, integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.get_attendee_profile(integer) TO service_role;
GRANT EXECUTE ON FUNCTION public.save_attendee_profile(integer, text, text, integer) TO service_role;

COMMIT;
